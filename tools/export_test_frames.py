#!/usr/bin/env python3
"""Export real HCRL frames as a C header the firmware replays.

Wokwi has no CAN transceiver, so the firmware needs frames from somewhere. We
could hardcode a made-up sequence, but then the serial output would only prove
the code runs, not that it works. Instead we export REAL frames from the HCRL
test split, WITH their ground-truth labels, so the ESP32 prints its verdict next
to the right answer and the numbers in the README can be checked.

Two things matter about the selection:

  1. It comes from the TEST split. These are frames the model has never seen.
  2. It spans an attack burst boundary, with clean traffic either side, so the
     serial log shows the actual transition rather than just a wall of alerts.

Timestamps are converted to RELATIVE MICROSECONDS. The original values are Unix
epoch seconds (~1.478e9) in float64; a 32-bit float at that magnitude has a
spacing of about 128 seconds, so every inter-frame gap would round to zero on
device and half the features would be dead. Relative uint32 microseconds are
exact for 71 minutes, which is far more than we replay.

    python tools/export_test_frames.py
    python tools/export_test_frames.py --capture DoS_dataset --count 1500
"""

import argparse
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from securecan import dataset  # noqa: E402

PROCESSED = ROOT / "data" / "processed"
OUT = ROOT / "firmware" / "esp32" / "src" / "test_frames.h"

CLASS_NAMES = ["Normal", "DoS", "Fuzzy", "Gear", "RPM"]


def pick_window(ts, label, count, lead=0.4):
    """Find a window of `count` frames straddling the start of an attack burst.

    `lead` seconds of clean traffic go in front of the burst so the log shows
    normal -> attack rather than starting mid-flood.
    """
    atk = np.flatnonzero(label != 0)
    if not len(atk):
        return 0, min(count, len(ts))

    # burst starts: an injected frame with no injected frame in the preceding
    # 0.5 s. Same definition evaluate.py uses for the detection-delay metric.
    gaps = np.diff(ts[atk])
    starts = np.concatenate([atk[:1], atk[1:][gaps > 0.5]])

    # prefer a burst far enough into the window that there is room for `lead`
    for s in starts:
        t0 = ts[s] - lead
        begin = int(np.searchsorted(ts, t0, side="left"))
        if begin + count <= len(ts):
            return begin, begin + count

    return 0, min(count, len(ts))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--capture", default="RPM_dataset",
                    help="which parsed capture to take frames from")
    ap.add_argument("--count", type=int, default=1200,
                    help="how many frames to export (flash is the limit)")
    args = ap.parse_args()

    p = PROCESSED / f"{args.capture}.npz"
    if not p.exists():
        raise SystemExit(f"missing {p} -- run parse.py first")

    d = np.load(p)
    ts, can_id, dlc, data, label = (d["ts"], d["can_id"], d["dlc"],
                                    d["data"], d["label"])

    # test split of the attack-bearing region: frames the model never trained on
    sl = dataset.split_slices(label)["test"][0]
    ts, can_id, dlc, data, label = (ts[sl], can_id[sl], dlc[sl],
                                    data[sl], label[sl])

    a, b = pick_window(ts, label, args.count)
    ts, can_id, dlc, data, label = (ts[a:b], can_id[a:b], dlc[a:b],
                                    data[a:b], label[a:b])
    n = len(ts)

    t_us = np.round((ts - ts[0]) * 1e6).astype(np.uint64)
    if t_us[-1] >= 2**32:
        raise SystemExit("window longer than the uint32 microsecond range")
    t_us = t_us.astype(np.uint32)

    counts = np.bincount(label, minlength=5)
    span = (ts[-1] - ts[0])

    print(f"  {args.capture}: test-split frames {a:,}-{b:,}")
    print(f"  {n:,} frames over {span:.3f} s "
          f"({n / max(span, 1e-9):,.0f} frames/s)")
    print("  " + "  ".join(f"{CLASS_NAMES[i]}={int(counts[i]):,}"
                           for i in range(5) if counts[i]))

    L = [
        "// Generated by tools/export_test_frames.py -- do not edit by hand.",
        "//",
        f"// {n} real CAN frames from the {args.capture} TEST split (frames "
        f"{a}-{b}),",
        "// i.e. frames the model was never trained on. Labels are HCRL's ground",
        "// truth and are printed next to the verdict so the firmware's output can",
        "// be checked rather than just believed.",
        "//",
        f"// span {span:.3f} s, {n / max(span, 1e-9):,.0f} frames/s, "
        + " ".join(f"{CLASS_NAMES[i]}={int(counts[i])}"
                   for i in range(5) if counts[i]),
        "//",
        "// Timestamps are microseconds relative to the first frame. The source",
        "// values are Unix epoch seconds in float64; 32-bit float at 1.478e9 has",
        "// a spacing of ~128 s, so absolute time on device would round every gap",
        "// to zero and kill the timing features.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define SC_N_TEST_FRAMES {n}",
        "",
        f"const uint32_t SC_TEST_T_US[SC_N_TEST_FRAMES] = {{",
    ]

    for i in range(0, n, 10):
        L.append("    " + " ".join(f"{v}," for v in t_us[i:i + 10]))
    L += ["};", ""]

    L.append(f"const uint16_t SC_TEST_ID[SC_N_TEST_FRAMES] = {{")
    for i in range(0, n, 12):
        L.append("    " + " ".join(f"0x{v:03X}," for v in can_id[i:i + 12]))
    L += ["};", ""]

    L.append(f"const uint8_t SC_TEST_DLC[SC_N_TEST_FRAMES] = {{")
    for i in range(0, n, 24):
        L.append("    " + " ".join(f"{v}," for v in dlc[i:i + 24]))
    L += ["};", ""]

    L.append("// 0=Normal 1=DoS 2=Fuzzy 3=Gear 4=RPM")
    L.append(f"const uint8_t SC_TEST_LABEL[SC_N_TEST_FRAMES] = {{")
    for i in range(0, n, 24):
        L.append("    " + " ".join(f"{v}," for v in label[i:i + 24]))
    L += ["};", ""]

    L.append(f"const uint8_t SC_TEST_DATA[SC_N_TEST_FRAMES][8] = {{")
    for row in data:
        L.append("    {" + ", ".join(f"0x{b:02X}" for b in row) + "},")
    L += ["};", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L))

    size = OUT.stat().st_size
    # 4 + 2 + 1 + 1 + 8 bytes per frame once compiled into flash
    flash = n * 16
    print(f"\n-> {OUT.relative_to(ROOT)}  ({size / 1024:.0f} KB source, "
          f"~{flash / 1024:.0f} KB in flash)")


if __name__ == "__main__":
    main()
